const LanguageContext = createContext<LanguageContextValue>({
  language: "en",
  setLanguage: () => {},
  t: (text) => text,
});

// Loads and persists the chosen language, and keeps document metadata in sync.
export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const [language, setLanguage] = useState<Language>("en");
  const [isLanguageLoaded, setIsLanguageLoaded] = useState(false);

  // Restore a saved language once in the browser, after the initial render.
  useEffect(() => {
    const savedLanguage = window.localStorage.getItem("wavoko-language");
    if (savedLanguage === "fr" || savedLanguage === "en") setLanguage(savedLanguage);
    setIsLanguageLoaded(true);
  }, []);

  // Update the page language, title, and description whenever route or language changes.
  useEffect(() => {
    if (!isLanguageLoaded) return;
    document.documentElement.lang = language;
    const title =
      language === "fr"
        ? "Wavoko — Ouvrir les portes des possibles"
        : "Wavoko — Opening doors to possibility";
    const descriptionText = language === "fr"
      ? "Votre prochain emploi, votre prochain talent et votre prochain objectif financier."
      : "Your next job. Your next great hire. Your next financial milestone.";
    const syncMetadata = () => {
      if (document.title !== title) document.title = title;
      const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
      if (description?.content !== descriptionText) description?.setAttribute("content", descriptionText);
    };
    const metadataObserver = new MutationObserver(syncMetadata);
    metadataObserver.observe(document.head, { childList: true, subtree: true, characterData: true });
    syncMetadata();
    window.localStorage.setItem("wavoko-language", language);
    return () => metadataObserver.disconnect();
  }, [isLanguageLoaded, language, pathname]);

  // Return the French version when available; otherwise leave the original text unchanged.
  const t = (text: string) => (language === "fr" ? translations[text] ?? text : text);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

// Shared hook used by components to read the language and translate interface text.
export function useLanguage() {
  return useContext(LanguageContext);
}
